"use strict";
module.exports = `
CREATE TABLE IF NOT EXISTS state (id INTEGER PRIMARY KEY CHECK(id=1), json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS users (id TEXT PRIMARY KEY, name TEXT NOT NULL, username TEXT UNIQUE NOT NULL, role TEXT NOT NULL, salt TEXT NOT NULL, hash TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS audit (id INTEGER PRIMARY KEY AUTOINCREMENT, at TEXT NOT NULL, actor TEXT NOT NULL, action TEXT NOT NULL, details TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS requests (key TEXT PRIMARY KEY, user_id TEXT NOT NULL, fingerprint TEXT NOT NULL, response TEXT NOT NULL, at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS cloud_backups (name TEXT PRIMARY KEY, at TEXT NOT NULL, json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS login_attempts (key TEXT PRIMARY KEY, count INTEGER NOT NULL, until_ms INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS transfers (id TEXT PRIMARY KEY, user_id TEXT NOT NULL, kind TEXT NOT NULL, parts INTEGER NOT NULL, bytes INTEGER NOT NULL, checksum TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS transfer_parts (transfer_id TEXT NOT NULL, position INTEGER NOT NULL, payload TEXT NOT NULL, PRIMARY KEY(transfer_id,position));
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires);
CREATE INDEX IF NOT EXISTS transfers_expiry ON transfers(expires);
`;

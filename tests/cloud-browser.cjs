"use strict";
const { chromium } = require("playwright");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const assert = require("node:assert/strict");
const { randomUUID, createHash } = require("node:crypto");
const { createClient } = require("@libsql/client/web");
const { createApp } = require("../server.cjs");
const { createCloudStorage } = require("../cloud-storage.cjs");
const { createTursoEmulator } = require("./helpers/turso-emulator.cjs");
(async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "aurea-cloud-browser-"));
  const emulator = await createTursoEmulator(path.join(dir, "base.sqlite"));
  const storage = await createCloudStorage({ url: emulator.url, client: createClient({ url: emulator.url, authToken: "prueba", intMode: "number" }) });
  const setupKey = "clave-inicial-de-pruebas-1234567890";
  const app = createApp({ storage, setupKey });
  await app.ready;
  await new Promise(r => app.server.listen(0, "127.0.0.1", r));
  const base = "http://127.0.0.1:" + app.server.address().port;
  let browser;
  try {
    browser = await chromium.launch({ headless: true, channel: process.env.TALLER_BROWSER || "msedge" });
    const context = await browser.newContext();
    const page = await context.newPage(); page.setDefaultTimeout(20000);
    const errors = []; page.on("pageerror", e => errors.push(e.message));
    await page.goto(base);
    await page.locator("[name=setupKey]").fill(setupKey);
    await page.locator("[name=workshop]").fill("Taller en Vercel");
    await page.locator("[name=name]").fill("Administrador nube");
    await page.locator("[name=username]").fill("admin");
    await page.locator("[name=password]").fill("1234");
    assert.match(await page.locator(".login-form footer").innerText(), /Necesitas conexión a internet/);
    await page.locator("#auth-form button[type=submit]").click();
    await page.locator("#page").waitFor();
    await page.locator("[data-nav=settings]").click();
    await page.locator("[data-action=restore-backup]").waitFor();
    const backup = await page.evaluate(async () => await window.TallerTransport.request("/api/backup"));
    backup.state.clients = Array.from({ length: 2600 }, (_, i) => ({ id: randomUUID(), name: "Cliente remoto " + i, document: String(i), phone: "", email: "", notes: "áéíóú ñ ".repeat(200), createdAt: new Date().toISOString() }));
    const { checksum, ...content } = backup;
    backup.checksum = createHash("sha256").update(JSON.stringify(content)).digest("hex");
    const file = Buffer.from(JSON.stringify(backup)); assert(file.length > 4.5 * 1024 * 1024);
    await page.locator("[data-action=restore-backup]").click();
    await page.locator("[name=backup]").setInputFiles({ name: "copia.json", mimeType: "application/json", buffer: file });
    await page.locator("#dialog [name=password]").fill("1234");
    await page.locator("[name=confirmed]").check();
    await page.locator("#modal-form button[type=submit]").click();
    await page.waitForFunction(() => !document.querySelector("#dialog").open || !!document.querySelector("#modal-form .form-error")?.textContent);
    if (await page.locator("#dialog").isVisible()) throw new Error(await page.locator("#modal-form .form-error").innerText());
    const result = await page.evaluate(async () => (await window.TallerTransport.request("/api/state")).state.clients.length);
    assert.equal(result, 2600);
    const download = page.waitForEvent("download");
    await page.locator("[data-action=download-backup]").click();
    const saved = await download;
    const exported = JSON.parse(fs.readFileSync(await saved.path(), "utf8"));
    assert.equal(exported.state.clients.length, 2600);
    assert.deepEqual(errors, []);
    console.log("Nube verificada en navegador: clave inicial, sesión, restauración y descarga de más de 4,5 MB por la interfaz.");
  } finally {
    await browser?.close(); await new Promise(r => app.server.close(r)); await emulator.close(); fs.rmSync(dir, { recursive: true, force: true });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
